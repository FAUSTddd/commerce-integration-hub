<?php

declare(strict_types=1);

namespace App\Tests\Integration\Repository;

use App\Entity\ImportRun;
use App\Repository\ImportRunRepository;
use Doctrine\DBAL\Connection;
use Doctrine\DBAL\DriverManager;
use Doctrine\ORM\EntityManagerInterface;
use Doctrine\ORM\Tools\SchemaTool;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;

final class ImportRunRepositoryIntegrationTest extends KernelTestCase
{
    private EntityManagerInterface $entityManager;
    private ImportRunRepository $repository;
    private Connection $primaryConn;

    protected function setUp(): void
    {
        self::bootKernel();
        $container = static::getContainer();

        $this->entityManager = $container->get(EntityManagerInterface::class);
        $this->repository = $container->get(ImportRunRepository::class);
        $this->primaryConn = $this->entityManager->getConnection();

        $schemaTool = new SchemaTool($this->entityManager);
        $metadata = $this->entityManager->getMetadataFactory()->getAllMetadata();
        $schemaTool->dropSchema($metadata);
        $schemaTool->createSchema($metadata);

        $this->primaryConn->executeStatement('CREATE TABLE IF NOT EXISTS messenger_messages (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
            body TEXT NOT NULL,
            headers TEXT NOT NULL,
            queue_name VARCHAR(190) NOT NULL,
            created_at TIMESTAMP(0) WITH TIME ZONE NOT NULL,
            available_at TIMESTAMP(0) WITH TIME ZONE NOT NULL,
            delivered_at TIMESTAMP(0) WITH TIME ZONE DEFAULT NULL
        )');
        $this->primaryConn->executeStatement('DELETE FROM messenger_messages');
        $this->primaryConn->executeStatement('DELETE FROM import_runs');

        $this->primaryConn->executeStatement(
            "CREATE UNIQUE INDEX IF NOT EXISTS uniq_import_runs_active_type_filename
             ON import_runs (type, filename)
             WHERE status IN ('PENDING', 'PROCESSING')"
        );
    }

    protected function tearDown(): void
    {
        parent::tearDown();
        $this->entityManager->close();
    }

    public function testTryCreateActiveRunAllocatesIdWhenNoActiveRun(): void
    {
        $runId = $this->repository->tryCreateActiveRun('catalog', 'test.xml', 'hash_123');

        $this->assertNotNull($runId);
        $this->assertGreaterThan(0, $runId);

        $run = $this->repository->find($runId);
        $this->assertNotNull($run);
        $this->assertSame('catalog', $run->getType());
        $this->assertSame('test.xml', $run->getFilename());
        $this->assertSame(ImportRun::STATUS_PENDING, $run->getStatus());
    }

    public function testTryCreateActiveRunReturnsNullWhenPendingOrProcessingExists(): void
    {
        // 1. First call allocates ID
        $runId1 = $this->repository->tryCreateActiveRun('catalog', 'orders.xml', 'hash_abc');
        $this->assertNotNull($runId1);

        // 2. Second call with same type and filename while first is PENDING returns null
        $runId2 = $this->repository->tryCreateActiveRun('catalog', 'orders.xml', 'hash_def');
        $this->assertNull($runId2);

        // 3. Transition first run to PROCESSING -> still returns null
        $run1 = $this->repository->find($runId1);
        $this->assertNotNull($run1);
        $run1->setStatus(ImportRun::STATUS_PROCESSING);
        $this->repository->save($run1);

        $runId3 = $this->repository->tryCreateActiveRun('catalog', 'orders.xml', 'hash_ghi');
        $this->assertNull($runId3);
    }

    public function testTerminalStatusesSuccessAndFailedAllowNewRunCreation(): void
    {
        // 1. Create run and mark SUCCESS
        $runId1 = $this->repository->tryCreateActiveRun('offers', 'prices.xml', 'hash_1');
        $this->assertNotNull($runId1);
        $run1 = $this->repository->find($runId1);
        $this->assertNotNull($run1);
        $run1->setStatus(ImportRun::STATUS_SUCCESS);
        $this->repository->save($run1);

        // Subsequent call for same file now succeeds
        $runId2 = $this->repository->tryCreateActiveRun('offers', 'prices.xml', 'hash_2');
        $this->assertNotNull($runId2);
        $this->assertNotSame($runId1, $runId2);

        // Mark second run FAILED
        $run2 = $this->repository->find($runId2);
        $this->assertNotNull($run2);
        $run2->setStatus(ImportRun::STATUS_FAILED);
        $this->repository->save($run2);

        // Subsequent call for same file after FAILED also succeeds
        $runId3 = $this->repository->tryCreateActiveRun('offers', 'prices.xml', 'hash_3');
        $this->assertNotNull($runId3);
        $this->assertNotSame($runId2, $runId3);

        // Verify history preserved: exactly 3 rows in database
        $totalCount = (int) $this->primaryConn->fetchOne('SELECT COUNT(*) FROM import_runs WHERE filename = ?', ['prices.xml']);
        $this->assertSame(3, $totalCount);
    }

    public function testCompensateFailedEnqueueCasAtomicity(): void
    {
        $runId = $this->repository->tryCreateActiveRun('catalog', 'compensate.xml', 'hash_c');
        $this->assertNotNull($runId);

        // CAS on PENDING -> succeeds
        $compensated = $this->repository->compensateFailedEnqueue($runId, 'Enqueue failed');
        $this->assertTrue($compensated);

        $run = $this->repository->find($runId);
        $this->assertNotNull($run);
        $this->assertSame(ImportRun::STATUS_FAILED, $run->getStatus());
        $this->assertStringContainsString('Enqueue failed', (string) $run->getErrorMessage());

        // Second compensation on now-FAILED run -> returns false (0 rows affected)
        $secondAttempt = $this->repository->compensateFailedEnqueue($runId, 'Another error');
        $this->assertFalse($secondAttempt);

        // Test CAS on PROCESSING run -> must return false and not clobber PROCESSING
        $runId2 = $this->repository->tryCreateActiveRun('catalog', 'processing.xml', 'hash_p');
        $this->assertNotNull($runId2);
        $run2 = $this->repository->find($runId2);
        $this->assertNotNull($run2);
        $run2->setStatus(ImportRun::STATUS_PROCESSING);
        $this->repository->save($run2);

        $processingCompensated = $this->repository->compensateFailedEnqueue($runId2, 'Clobber attempt');
        $this->assertFalse($processingCompensated);

        $run2Reloaded = $this->repository->find($runId2);
        $this->assertNotNull($run2Reloaded);
        $this->assertSame(ImportRun::STATUS_PROCESSING, $run2Reloaded->getStatus());
    }

    public function testConcurrentTryCreateActiveRunViaTwoIndependentDbalConnections(): void
    {
        // Obtain independent secondary DBAL connection
        $params = $this->primaryConn->getParams();
        $secondaryConn = DriverManager::getConnection($params);

        $sql = <<<SQL
            INSERT INTO import_runs (type, filename, file_hash, status, items_count, created_at)
            VALUES (:type, :filename, :fileHash, 'PENDING', 0, NOW())
            ON CONFLICT (type, filename) WHERE status IN ('PENDING', 'PROCESSING')
            DO NOTHING
            RETURNING id
        SQL;

        // Conn 1 begins transaction and locks row via INSERT
        $this->primaryConn->beginTransaction();
        $res1 = $this->primaryConn->fetchOne($sql, [
            'type' => 'catalog',
            'filename' => 'concurrent.xml',
            'fileHash' => 'hash_c1',
        ]);
        $this->assertNotFalse($res1);
        $runId1 = (int) $res1;
        $this->assertGreaterThan(0, $runId1);

        // Conn 2 executes simultaneously prior to Conn 1 commit.
        // PostgreSQL partially-indexed ON CONFLICT waits on the uncommitted tuple or immediately yields DO NOTHING upon commit.
        // We test the concurrency boundary: Conn 1 commits, then Conn 2 completes.
        $this->primaryConn->commit();

        $res2 = $secondaryConn->fetchOne($sql, [
            'type' => 'catalog',
            'filename' => 'concurrent.xml',
            'fileHash' => 'hash_c2',
        ]);

        // Conn 2 must return false/null due to ON CONFLICT DO NOTHING
        $this->assertTrue($res2 === false || $res2 === null);

        // Verify database state: strictly 1 row in import_runs
        $activeCount = (int) $this->primaryConn->fetchOne(
            "SELECT COUNT(*) FROM import_runs WHERE filename = 'concurrent.xml' AND status IN ('PENDING', 'PROCESSING')"
        );
        $this->assertSame(1, $activeCount);

        $secondaryConn->close();
    }
}
