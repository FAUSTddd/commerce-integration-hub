<?php

declare(strict_types=1);

namespace App\Tests\Integration;

use App\Domain\Model\Product;
use App\Domain\Model\ProductVariant;
use App\Domain\Repository\ProductRepositoryInterface;
use App\Domain\Repository\ProductVariantRepositoryInterface;
use Doctrine\DBAL\Connection;
use Doctrine\ORM\EntityManagerInterface;
use Doctrine\ORM\Tools\SchemaTool;
use FaustDDD\Symfony1cImport\Application\Command\ImportCatalogCommand;
use FaustDDD\Symfony1cImport\Application\Command\ImportOffersCommand;
use Symfony\Bundle\FrameworkBundle\Console\Application;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;
use Symfony\Component\Console\Input\ArrayInput;
use Symfony\Component\Console\Output\NullOutput;
use Symfony\Component\Messenger\MessageBusInterface;

class ImportIntegrationTest extends KernelTestCase
{
    private ?EntityManagerInterface $entityManager = null;
    private ?MessageBusInterface $messageBus = null;
    private ?ProductRepositoryInterface $productRepository = null;
    private ?ProductVariantRepositoryInterface $variantRepository = null;

    protected function setUp(): void
    {
        self::bootKernel();
        $container = static::getContainer();

        $this->entityManager = $container->get(EntityManagerInterface::class);
        $this->messageBus = $container->get(MessageBusInterface::class);
        $this->productRepository = $container->get(ProductRepositoryInterface::class);
        $this->variantRepository = $container->get(ProductVariantRepositoryInterface::class);

        // Prepare schema in DB
        $schemaTool = new SchemaTool($this->entityManager);
        $metadata = $this->entityManager->getMetadataFactory()->getAllMetadata();
        $schemaTool->dropSchema($metadata);
        $schemaTool->createSchema($metadata);

        // Ensure messenger_messages table exists in test DB
        $this->entityManager->getConnection()->executeStatement('CREATE TABLE IF NOT EXISTS messenger_messages (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
            body TEXT NOT NULL,
            headers TEXT NOT NULL,
            queue_name VARCHAR(190) NOT NULL,
            created_at TIMESTAMP(0) WITH TIME ZONE NOT NULL,
            available_at TIMESTAMP(0) WITH TIME ZONE NOT NULL,
            delivered_at TIMESTAMP(0) WITH TIME ZONE DEFAULT NULL
        )');
        $this->entityManager->getConnection()->executeStatement('DELETE FROM messenger_messages');
    }

    protected function tearDown(): void
    {
        parent::tearDown();
        $this->entityManager?->close();
        $this->entityManager = null;
    }

    private function runWorker(): void
    {
        $application = new Application(self::$kernel);
        $application->setAutoExit(false);
        $input = new ArrayInput([
            'command' => 'messenger:consume',
            'receivers' => ['async'],
            '--limit' => 1,
            '--time-limit' => 10,
            '--quiet' => true,
        ]);
        $output = new NullOutput();
        $application->run($input, $output);
    }

    public function testEndToEndCatalogAndOffersLifecycle(): void
    {
        $fixturesDir = dirname(__DIR__) . '/Fixtures';
        $catalogXml = $fixturesDir . '/import_catalog.xml';
        $offersXml = $fixturesDir . '/import_offers.xml';
        $offersUpdatedXml = $fixturesDir . '/import_offers_updated.xml';

        // 1. First catalog import
        $this->messageBus->dispatch(new ImportCatalogCommand($catalogXml));
        $this->runWorker();
        $this->entityManager->clear();

        $p1 = $this->productRepository->findByExternalId('prod-1001');
        $this->assertNotNull($p1);
        $this->assertSame('Кофемашина DeLonghi Magnifica S', $p1->getName());
        $this->assertSame('ART-1001', $p1->getSku());

        $p2 = $this->productRepository->findByExternalId('prod-1002');
        $this->assertNotNull($p2);

        $p3 = $this->productRepository->findByExternalId('prod-1003');
        $this->assertNotNull($p3);
        $this->assertNull($p3->getSku());

        // 2. Second catalog import (idempotency check)
        $this->messageBus->dispatch(new ImportCatalogCommand($catalogXml));
        $this->runWorker();
        $this->entityManager->clear();

        $countProducts = (int) $this->entityManager->getConnection()
            ->fetchOne('SELECT COUNT(*) FROM products');
        $this->assertSame(3, $countProducts, 'Duplicate products must not be created on re-import');

        // 3. First offers import
        $this->messageBus->dispatch(new ImportOffersCommand($offersXml));
        $this->runWorker();
        $this->entityManager->clear();

        $v1 = $this->variantRepository->findByExternalId('prod-1001#var-1');
        $this->assertNotNull($v1);
        $this->assertSame(3599050, $v1->getPriceAmount()); // 35990.50 RUB
        $this->assertSame('15.000', $v1->getStock());
        $this->assertSame('RUB', $v1->getCurrency());
        $this->assertSame('prod-1001', $v1->getProduct()->getExternalId());

        $v2 = $this->variantRepository->findByExternalId('prod-1002');
        $this->assertNotNull($v2);
        $this->assertSame(499900, $v2->getPriceAmount());
        $this->assertSame('42.500', $v2->getStock());

        // Offers for non-existing products must be skipped safely
        $vNonExisting = $this->variantRepository->findByExternalId('non-existing-prod-999#var-1');
        $this->assertNull($vNonExisting);

        $countVariants = (int) $this->entityManager->getConnection()
            ->fetchOne('SELECT COUNT(*) FROM product_variants');
        $this->assertSame(2, $countVariants);

        // 4. Offers update import (price & stock mutation)
        $this->messageBus->dispatch(new ImportOffersCommand($offersUpdatedXml));
        $this->runWorker();
        $this->entityManager->clear();

        $v1Updated = $this->variantRepository->findByExternalId('prod-1001#var-1');
        $this->assertNotNull($v1Updated);
        $this->assertSame(3299000, $v1Updated->getPriceAmount()); // Updated to 32990.00
        $this->assertSame('8.000', $v1Updated->getStock());        // Updated to 8.000

        $v2Updated = $this->variantRepository->findByExternalId('prod-1002');
        $this->assertNotNull($v2Updated);
        $this->assertSame(450000, $v2Updated->getPriceAmount());  // Updated to 4500.00
        $this->assertSame('50.000', $v2Updated->getStock());       // Updated to 50.000

        // Total count must remain 2 (updates, no duplications)
        $finalCountVariants = (int) $this->entityManager->getConnection()
            ->fetchOne('SELECT COUNT(*) FROM product_variants');
        $this->assertSame(2, $finalCountVariants);
    }
}
